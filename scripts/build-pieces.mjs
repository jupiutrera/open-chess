// Downloads the open piece sets from lichess-org/lila and writes src/pieces.css.
// Licences: see README (most sets are CC BY-NC-SA 4.0, chessnut Apache 2.0, cburnett GPL).
import { mkdirSync, writeFileSync, existsSync } from 'node:fs'

export const SETS = ['staunty', 'fresca', 'tatiana', 'maestro', 'california', 'cardinal', 'gioco', 'chessnut', 'cburnett']
const ROLES = { P: 'pawn', N: 'knight', B: 'bishop', R: 'rook', Q: 'queen', K: 'king' }
const BASE = 'https://raw.githubusercontent.com/lichess-org/lila/master/public/piece'

let css = '/* Generated by scripts/build-pieces.mjs */\n'
for (const set of SETS) {
  const dir = `src/assets/pieces/${set}`
  mkdirSync(dir, { recursive: true })
  for (const c of ['w', 'b']) {
    for (const [letter, role] of Object.entries(ROLES)) {
      const file = `${dir}/${c}${letter}.svg`
      if (!existsSync(file)) {
        const res = await fetch(`${BASE}/${set}/${c}${letter}.svg`)
        if (!res.ok) throw new Error(`${set}/${c}${letter}: ${res.status}`)
        writeFileSync(file, Buffer.from(await res.arrayBuffer()))
      }
      css += `:root[data-pieces='${set}'] .cg-wrap piece.${role}.${c === 'w' ? 'white' : 'black'} { background-image: url('./assets/pieces/${set}/${c}${letter}.svg'); }\n`
    }
  }
}
writeFileSync('src/pieces.css', css)
console.log('pieces:', SETS.join(', '))
